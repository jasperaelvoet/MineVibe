export class Canvas {
  readonly w: number;
  readonly h: number;
  readonly #px: Uint8Array;

  constructor(w: number, h: number, bg: Rgb = [255, 255, 255]) {
    this.w = w;
    this.h = h;
    this.#px = new Uint8Array(w * h * 3);
    this.rect(0, 0, w, h, bg);
  }

  rect(x: number, y: number, w: number, h: number, c: Rgb): this {
    const x0 = Math.max(0, Math.floor(x));
    const y0 = Math.max(0, Math.floor(y));
    const x1 = Math.min(this.w, Math.floor(x + w));
    const y1 = Math.min(this.h, Math.floor(y + h));
    for (let yy = y0; yy < y1; yy++) {
      for (let xx = x0; xx < x1; xx++) {
        const i = (yy * this.w + xx) * 3;
        this.#px[i] = c[0];
        this.#px[i + 1] = c[1];
        this.#px[i + 2] = c[2];
      }
    }
    return this;
  }

  /** A 1-pixel-scaled outline. */
  frame(x: number, y: number, w: number, h: number, c: Rgb, t = 2): this {
    return this.rect(x, y, w, t, c)
      .rect(x, y + h - t, w, t, c)
      .rect(x, y, t, h, c)
      .rect(x + w - t, y, t, h, c);
  }

  /** Draws text with its top-left at x,y; returns the width drawn. */
  text(x: number, y: number, s: string, c: Rgb, scale = 2): number {
    let cx = x;
    for (const ch of s.toUpperCase()) {
      const g = GLYPHS[ch] ?? GLYPHS['?'];
      if (g) {
        for (let row = 0; row < 7; row++) {
          const line = g[row] ?? '';
          for (let col = 0; col < 5; col++) {
            if (line[col] === '#') this.rect(cx + col * scale, y + row * scale, scale, scale, c);
          }
        }
      }
      cx += 6 * scale;
    }
    return cx - x;
  }

  /** Width of `s` at `scale`. */
  static textWidth(s: string, scale = 2): number {
    return s.length * 6 * scale;
  }

  png(): Uint8Array {
    return encodePng(this.w, this.h, this.#px);
  }
}

const CRC_TABLE = (() => {
  const t = new Uint32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    t[n] = c >>> 0;
  }
  return t;
})();

function crc32(bytes: Uint8Array): number {
  let c = 0xffffffff;
  for (const b of bytes) c = (CRC_TABLE[(c ^ b) & 0xff] as number) ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}

function chunk(type: string, data: Uint8Array): Uint8Array {
  const out = new Uint8Array(12 + data.length);
  const view = new DataView(out.buffer);
  view.setUint32(0, data.length);
  const typeBytes = new TextEncoder().encode(type);
  out.set(typeBytes, 4);
  out.set(data, 8);
  view.setUint32(8 + data.length, crc32(out.subarray(4, 8 + data.length)));
  return out;
}

/** An 8-bit RGB PNG of `rgb` (row-major, 3 bytes per pixel). */
export function encodePng(w: number, h: number, rgb: Uint8Array): Uint8Array {
  const raw = new Uint8Array(h * (w * 3 + 1));
  for (let y = 0; y < h; y++) {
    raw[y * (w * 3 + 1)] = 0; // filter: none
    raw.set(rgb.subarray(y * w * 3, (y + 1) * w * 3), y * (w * 3 + 1) + 1);
  }
  const ihdr = new Uint8Array(13);
  const v = new DataView(ihdr.buffer);
  v.setUint32(0, w);
  v.setUint32(4, h);
  ihdr[8] = 8; // bit depth
  ihdr[9] = 2; // colour type: RGB
  const sig = new Uint8Array([137, 80, 78, 71, 13, 10, 26, 10]);
  const parts = [
    sig,
    chunk('IHDR', ihdr),
    chunk('IDAT', deflateSync(raw, { level: 6 })),
    chunk('IEND', new Uint8Array()),
  ];
  const total = parts.reduce((s, p) => s + p.length, 0);
  const out = new Uint8Array(total);
  let off = 0;
  for (const p of parts) {
    out.set(p, off);
    off += p.length;
  }
  return out;
}
